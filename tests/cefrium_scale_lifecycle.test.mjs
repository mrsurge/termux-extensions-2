import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read = name => readFileSync(new URL('../android/cefrium/src/main/java/com/termux/extensions/'+name, import.meta.url),'utf8');
const activity=read('MainActivity.kt');
const policy=read('CefriumViewportPolicy.kt');
const chrome=readFileSync(new URL('../android/termux/src/main/java/com/termux/extensions/TermuxChromeSurface.kt',import.meta.url),'utf8');
assert.match(chrome,/CefriumBrowser.createWithSurface\(context, true\)/);
assert.match(activity,/val inspector = existingInspector \?: CefriumBrowser.createWithSurface\(this, BuildConfig.TE2_TERMUX\)/);
assert.match(activity,/val processes = processesBrowser \?: CefriumBrowser.createWithSurface\(this, BuildConfig.TE2_TERMUX\)/);
assert.match(activity,/browser = CefriumBrowser.createWithSurface\(this\)/);
assert.match(activity,/observeRendererLifecycle = BuildConfig.TE2_TERMUX/);
const resume=activity.slice(activity.indexOf('override fun onResume()'),activity.indexOf('override fun onPause()'));
assert.ok(resume.indexOf('if (BuildConfig.TE2_TERMUX) mainViewport.reapply()') < resume.indexOf('browser.onResume()'));
assert.match(resume,/if \(!BuildConfig.TE2_TERMUX\) mainViewport.reapply\(\)/);
assert.match(policy,/if \(!observeRendererLifecycle\) browser.setPinchToZoomEnabled\(false\)/);
assert.match(policy,/SurfaceHolder.Callback/);
assert.match(policy,/override fun surfaceChanged/);
assert.match(policy,/WebContentsObserver\(next\)/);
assert.match(policy,/override fun onVisibilityChanged/);
assert.match(policy,/override fun onTopLevelNativeWindowChanged/);
assert.match(policy,/override fun renderFrameCreated/);
assert.match(policy,/override fun primaryPageChanged/);
assert.match(policy,/handler.post\(restoreAfterRenderer\)/);
assert.match(policy,/surfaceHolder\?\.removeCallback\(surfaceCallback\)/);
assert.match(policy,/contentsObserver\?\.observe\(null\)/);
assert.match(policy,/removeOnAttachStateChangeListener\(attachListener\)/);
assert.doesNotMatch(policy,/setDefaultZoomLevel|setZoomLevelForHost|setPageVisible|evaluateJavaScript/);
console.log('Termux native zoom lifecycle wiring guards passed (source checks, not device acceptance)');
