import { build, transform } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
process.chdir(fileURLToPath(new URL('.', import.meta.url)));
const common = { absWorkingDir: fileURLToPath(new URL('.', import.meta.url)), bundle: true, minify: true, format: 'esm', target: 'es2022', logLevel: 'info' };
await build({ ...common, entryPoints: ['terminal_drawer.ts'], outfile: '../../static/js/file_explorer_terminal.js',
  plugins: [{ name: 'codec', setup(build) { build.onResolve({ filter: /^\.\/wire_codec$/ }, () => ({ path: './file_explorer_codec.js', external: true })); } }] });
await build({ ...common, entryPoints: ['wire_codec.ts'], outfile: '../../static/js/file_explorer_codec.js' });
// Retain the shared helper URL without a second handwritten implementation.
await build({ ...common, entryPoints: ['src/menubar.ts'], outfile: '../../static/js/te_file_explorer_context.mjs' });
// Existing consumers retain the tab-helper URL; its authority is typed source.
await build({ ...common, entryPoints: ['src/tab_client.ts'], outfile: '../../static/js/file_explorer_tabs.mjs',
  plugins: [{ name: 'tab-codec', setup(build) { build.onResolve({ filter: /^\.\.\/wire_codec$/ }, () => ({ path: './file_explorer_codec.js', external: true })); } }] });
// One app bundle; shared resources and the isolated regex worker stay external.
// Standalone terminal/codec outputs retain their public compatibility contracts.
await build({ ...common, entryPoints: ['src/main.ts'], outfile: '../../static/js/file_explorer_main.js', external: ['/static/*'] });
const css = await readFile('src/styles.css', 'utf8');
const template = await readFile('src/template.html', 'utf8');
if (template.split('__FILE_EXPLORER_STYLES__').length !== 2) throw new Error('Expected one stylesheet placeholder');
const compiled = await transform(css, { loader: 'css', minify: true, target: 'es2022' });
await writeFile('template.html', '<!-- Generated by build.mjs; edit src/template.html and src/styles.css. -->\n' + template.replace('__FILE_EXPLORER_STYLES__', compiled.code.trim()));
