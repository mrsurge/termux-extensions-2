import path from 'node:path';
import { createRequire } from 'node:module';

const runtimeRoot = String(process.env.TERMINAL_STREAM_NODE_RUNTIME_ROOT || '').trim();
const runtimeRequire = runtimeRoot
  ? createRequire(path.join(runtimeRoot, 'package.json'))
  : createRequire(import.meta.url);

export function requireTerminalNodeModule(name) {
  try {
    return runtimeRequire(name);
  } catch (error) {
    const source = runtimeRoot || 'the source development node_modules tree';
    throw new Error(`Unable to load Terminal Node module ${name} from ${source}`, { cause: error });
  }
}
